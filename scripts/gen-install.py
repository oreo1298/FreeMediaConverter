"""Generate docs/INSTALL.md from docs/install/install.toml.

Usage: scripts/gen-install.py [--check]
--check exits non-zero if docs/INSTALL.md is not up to date (CI).
"""
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/install/install.toml"
OUT = ROOT / "docs/INSTALL.md"


def fill(cmd: str, data: dict) -> str:
    return cmd.replace("{base}", data["base"]).replace("{releases}", data["releases"])


def render(data: dict) -> str:
    out = [
        "<!-- Generated by scripts/gen-install.py from docs/install/install.toml. Do not edit. -->",
        "",
        "# Installing Retort",
        "",
        data["intro"].strip(),
        "",
    ]
    sections = [s for s in data["section"] if not s.get("hidden")]
    out += ["## Contents", ""]
    out += [f"- [{s['title']}](#{s['id']})" for s in sections]
    out.append("")
    for s in sections:
        out += [f'<a id="{s["id"]}"></a>', "", f"## {s['title']}", ""]
        if s.get("text"):
            out += [s["text"].strip(), ""]
        for step in s.get("step", []):
            if step.get("hidden"):
                continue
            if step.get("title"):
                out += [f"### {step['title']}", ""]
            if step.get("text"):
                out += [step["text"].strip(), ""]
            if step.get("commands"):
                out += ["```bash"] + [fill(c, data) for c in step["commands"]] + ["```", ""]
            if step.get("tip"):
                out += [f"> {step['tip']}", ""]
    out += [
        "---",
        "",
        "Every command above is run in a fresh container of the listed system by",
        "`scripts/test-docs.sh` (see [TESTING.md](TESTING.md)).",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    data = tomllib.loads(SRC.read_text(encoding="utf-8"))
    text = render(data)
    if "--check" in sys.argv:
        if OUT.read_text(encoding="utf-8") != text:
            print("docs/INSTALL.md is out of date: run scripts/gen-install.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
